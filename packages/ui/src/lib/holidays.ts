const TABLE = new Map<string, HolidayDay>();
for (const { blocks } of Object.values(YEARS))
  for (const [name, kind, dates] of blocks)
    for (const date of dates) TABLE.set(date, { name, off: kind === "off" });

/** 某天的法定放假 / 调休补班信息；没有收录或不涉及时返回 undefined。 */
export const holidayOf = (date: string) => TABLE.get(date);
/** 已收录放假安排的年份（升序）。 */
export const holidayYears = Object.keys(YEARS)
  .map(Number)
  .sort((a, b) => a - b);
export const holidaySource = (year: number) => YEARS[year]?.source;
